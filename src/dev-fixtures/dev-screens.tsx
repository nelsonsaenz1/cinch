export default function DevScreens() {
  const router = useRouter();

  if (!__DEV__) {
    return (
      <SafeAreaView className="flex-1 items-center justify-center bg-canvas">
        <Text variant="label">Not available.</Text>
      </SafeAreaView>
    );
  }

  return (
    <SafeAreaView className="flex-1 bg-canvas" edges={['top']}>
      <ScrollView contentContainerClassName="px-gutter pb-16">
        <Text variant="title" trim>
          Fixtures
        </Text>
        <Text variant="note" className="mt-2 text-muted">
          Every `__DEV__` route in the app. Deterministic by construction: no network, no clock, no
          spinner.
        </Text>

        {SECTIONS.map(([title, rows]) => (
          <View key={title} className="mt-7">
            <Text variant="eyebrow">{title}</Text>
            <Rule className="mb-1 mt-1.5" />
            {rows.map(([label, route]) => (
              <Pressable
                key={route}
                accessibilityRole="button"
                accessibilityLabel={label}
                // 44 pt is the floor everywhere, including here.
                className="min-h-tap flex-row items-center justify-between border-b border-rule py-3"
                onPress={() => router.push(route as Href)}>
                <Text variant="body">{label}</Text>
                <Text variant="note" className="text-muted">
                  {route.slice(1)}
                </Text>
              </Pressable>
            ))}
          </View>
        ))}
      </ScrollView>
    </SafeAreaView>
  );
}
