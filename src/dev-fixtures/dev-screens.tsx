/**
 * The index of every `__DEV__` fixture route — `cinch://dev-screens`.
 *
 * Wave 3 finished with 154 fixture routes and no way to reach any of them but
 * typing its deep link by hand. That is not a small inconvenience: a fixture
 * nobody can open is a fixture nobody checks, and the whole reason these exist
 * is that a drawn state is only settled once somebody has looked at it.
 *
 * This file used to be a throwaway preview of an item-detail stat grid, which
 * nothing linked to and nothing referenced. It is the list now.
 *
 * `tests/dev-route-index.test.ts` fails when a `dev-*` route exists that this
 * file does not name, so the index cannot quietly go stale the next time a lane
 * adds five frames. Adding a route means adding its line here — that is the
 * whole maintenance burden, and the test is what makes it non-optional.
 *
 * The paths are typed `string` and cast once at the push site rather than typed
 * `Href`. expo-router's `Href` union is generated by the dev server into
 * `.expo/types`, so it lags behind the filesystem until somebody runs Metro —
 * every route added in a packet is a type error in a packet that never starts
 * the server. The cast is not a hole here: the test above checks each path
 * against `readdirSync('src/app')`, which is the same filesystem the router
 * builds its routes from, and it checks BOTH directions. That is a stronger
 * guarantee than a union that can be stale.
 */
